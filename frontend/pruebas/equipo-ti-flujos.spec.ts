    await page.goto(`/panel/usuarios/${tecnico.id}`)
    await page.getByRole('button', { name: 'Editar datos', exact: true }).click()
    await page.getByLabel('Cargo', { exact: true }).fill('Mesa de ayuda municipal')
    await page.getByRole('button', { name: 'Guardar datos', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Modificar información' })).toBeVisible()
    const png = await page.evaluate(() => {
      const lienzo = document.createElement('canvas')
      lienzo.width = lienzo.height = 80
      const contexto = lienzo.getContext('2d')!
      contexto.fillStyle = '#0d9488'
      contexto.fillRect(0, 0, 80, 80)
      return lienzo.toDataURL('image/png').split(',')[1]
    })
    const foto = page.waitForResponse((respuesta) => respuesta.url().includes(`/usuarios/${tecnico.id}/foto`) && respuesta.request().method() === 'POST')
