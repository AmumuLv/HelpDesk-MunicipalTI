    await expect(horario.getByText('No laborable', { exact: true })).toHaveCount(2)
    await horario.getByRole('button', { name: 'Editar horario', exact: true }).click()
    await horario.getByLabel('Entrada Lunes 1').fill('09:00')
    await horario.getByRole('button', { name: 'Guardar horario', exact: true }).click()
    await expect(horario.getByText('09:00–13:00 · 14:00–17:00', { exact: true })).toBeVisible()
    await page.goto(`/panel/equipo-ti?tab=horarios&tecnico_id=${tecnico.id}`)
    const editor = page.getByRole('form', { name: `Horario de ${nombre}` })
    await expect(editor.getByText('09:00–13:00 · 14:00–17:00', { exact: true })).toBeVisible()
    await editor.getByRole('button', { name: 'Aplicar horario base' }).click()
    await editor.getByRole('button', { name: 'Guardar horario', exact: true }).click()
    await expect(editor.getByText('08:00–13:00 · 14:00–17:00', { exact: true })).toHaveCount(5)
    await page.getByRole('button', { name: 'Registrar ausencia', exact: true }).click()
    const dialogo = page.getByRole('dialog')
    await expect(dialogo.getByLabel('Técnico')).toHaveValue(tecnico.id)
    await dialogo.getByLabel('Tipo', { exact: true }).selectOption('Permiso')
    await dialogo.getByLabel('Desde').fill(dia)
    await dialogo.getByLabel('Hasta').fill(dia)
    await dialogo.getByLabel('Motivo').fill('Prueba de calendario TI')
    await dialogo.getByRole('button', { name: 'Registrar', exact: true }).click()
    await expect(dialogo).toBeHidden()
    await expect(page.getByRole('listitem').filter({ hasText: 'Prueba de calendario TI' })).toContainText(nombre)
    const estado = async () => {
      const datos = await (await request.get('/api/equipo-ti/panel', { headers })).json()
      return datos.items.find((t: { tecnico_id: string }) => t.tecnico_id === tecnico.id).estado
    }
    expect(await estado()).toBe('ausente')
    await page.getByRole('button', { name: 'Ausentes hoy: ver integrantes' }).click()
    await expect(page.getByLabel('Mostrar integrantes')).toHaveValue('ausentes')
    await expect(page.getByRole('link', { name: nombre, exact: true })).toBeVisible()
    await page.getByRole('tab', { name: 'Calendario semanal' }).click()
    await page.getByLabel('Persona en el calendario').selectOption(tecnico.id)
