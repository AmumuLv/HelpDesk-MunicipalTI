test('equipo, ausencias y calendario muestran diez registros por página', async ({ page }) => {
  await entrar(page, 'administrador')
  const integrantes = Array.from({ length: 12 }, (_, i) => ({ tecnico_id: `persona-${i}`, tecnico_nombre: `Integrante ${i + 1}`, estado: 'disponible', etiqueta: 'Disponible', carga_asignados: 1, carga_espera: 0, ausencias: [] }))
  await page.route('**/api/equipo-ti/panel', route => route.fulfill({ json: { items: integrantes } }))
  await page.route('**/api/ausencias*', route => route.fulfill({ json: { items: integrantes.map((t, i) => ({ id: `ausencia-${i}`, tecnico_id: t.tecnico_id, tecnico_nombre: t.tecnico_nombre, tipo: 'Permiso', inicio: '2099-01-01', fin: '2099-01-02' })) } }))
  await page.route('**/api/equipo-ti/calendario*', route => route.fulfill({ json: { items: integrantes.map(t => ({ ...t, carga_pendiente: 1, fecha: '2099-01-01', tramos: [], horas_disponibles: 0, vencimientos: 0 })) } }))
  await page.goto('/panel/equipo-ti')
  await expect(page.getByRole('link', { name: 'Integrante 10', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Integrante 11', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Integrante 11', exact: true })).toBeVisible()
  await page.getByLabel('Mostrar integrantes').selectOption('disponibles')
  await expect(page.getByRole('link', { name: 'Integrante 1', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Ausencias', exact: true }).click()
  await expect(page.getByRole('listitem').filter({ hasText: 'Integrante 11 ·' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click()
  await expect(page.getByRole('listitem').filter({ hasText: 'Integrante 11 ·' })).toBeVisible()
  await page.getByRole('tab', { name: 'Calendario semanal', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Integrante 11', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Integrante 11', exact: true })).toBeVisible()
})

