    await page.goto('/panel/equipo-ti')
    await page.getByRole('button', { name: 'Disponibles ahora: ver integrantes' }).click()
    await expect(page.getByLabel('Mostrar integrantes')).toHaveValue('disponibles')
    await page.getByRole('button', { name: 'Tickets abiertos: ver integrantes' }).click()
    await expect(page.getByLabel('Mostrar integrantes')).toHaveValue('pendientes')
    await page.getByRole('button', { name: 'Personas en el equipo: ver integrantes' }).click()
    const fila = page.getByRole('listitem').filter({ has: page.getByRole('link', { name: nombre, exact: true }) })
    await expect(fila).toContainText('Mesa de ayuda municipal')
    await expect(fila.locator('img')).toBeVisible()
    await fila.getByRole('link', { name: nombre, exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Datos de contacto' })).toBeVisible()
    await expect(page.getByText('999123456', { exact: true })).toBeVisible()
    await expect(page.getByText('102', { exact: true })).toBeVisible()
    await expect(page.locator(`a[href="/panel/oficinas/${tecnico.oficina_id}"]`).last()).toBeVisible()
    await expect(page.locator(`a[href="/panel/zonas/${tecnico.zona_id}"]`).last()).toBeVisible()
    await page.locator(`a[href="/panel/oficinas/${tecnico.oficina_id}"]`).last().click()
    await expect(page).toHaveURL(new RegExp(`/panel/oficinas/${tecnico.oficina_id}$`))
    await page.goBack()
    await page.locator(`a[href="/panel/zonas/${tecnico.zona_id}"]`).last().click()
    await expect(page).toHaveURL(new RegExp(`/panel/zonas/${tecnico.zona_id}$`))
    await page.goBack()
    await expect(page.locator('img[src^="blob:"]').first()).toBeVisible()
