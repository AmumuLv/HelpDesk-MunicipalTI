test('notificaciones filtra, pagina y marca un aviso sin abrirlo', async ({ page }) => {
  const leidas = new Set<string>()
  const items = Array.from({ length: 12 }, (_, i) => ({ id: String(i + 1), titulo: `Aviso de prueba ${i + 1}`, mensaje: `Detalle del aviso ${i + 1}`, creado_en: new Date().toISOString(), leida: false, tipo: 'mensaje', enlace: '/panel/tickets/abcdefabcdefabcdefabcdef' }))
  await page.route('**/api/notificaciones**', async ruta => {
    const url = new URL(ruta.request().url())
    if (ruta.request().method() === 'POST') {
      const ids = url.searchParams.getAll('ids')
      for (const item of items) if (!ids.length || ids.includes(item.id)) leidas.add(item.id)
      return ruta.fulfill({ json: { actualizadas: leidas.size } })
    }
    const lista = items.map(item => ({ ...item, leida: leidas.has(item.id) }))
    return ruta.fulfill({ json: { items: url.searchParams.get('solo_no_leidas') === 'true' ? lista.filter(item => !item.leida) : lista, no_leidas: 12 - leidas.size } })
  })
  await entrar(page, 'administrador')
  await page.getByRole('button', { name: /^Notificaciones/ }).click()
  await expect(page.getByText('Aviso de prueba 1', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Notificaciones siguientes', exact: true }).click()
  await expect(page.getByText('Aviso de prueba 6', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Notificaciones anteriores', exact: true }).click()
  const direccion = page.url()
  await page.getByRole('button', { name: 'Marcar como leída: Aviso de prueba 1', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Marcar como leída: Aviso de prueba 1', exact: true })).toHaveCount(0)
  expect(page.url()).toBe(direccion)
  await page.getByRole('button', { name: 'Sin leer', exact: true }).click()
  await expect(page.getByText('Aviso de prueba 1', { exact: true })).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('Biblioteca muestra cuatro artículos por página y un lector organizado', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await entrar(page, 'administrador')
  let articuloBase: Record<string, unknown> | undefined
  await page.route('**/api/kb/articulos?*', async (ruta) => {
    const respuesta = await ruta.fetch()
    const datos = await respuesta.json()
    const base = articuloBase ?? datos.items[0]
    articuloBase = base
    expect(base).toBeTruthy()
    const items = Array.from({ length: 8 }, (_, indice) => ({ ...base, id: String(indice).padStart(24, '0'), titulo: `Tutorial de monitor ${indice + 1}`, resumen: 'Comprueba los cables y selecciona la entrada de video correcta.', categoria: 'Tutoriales' }))
    const parametros = new URL(ruta.request().url()).searchParams
    expect(parametros.get('por_pagina')).toBe('4')
    const pagina = Number(parametros.get('pagina') ?? 1)
    await ruta.fulfill({ response: respuesta, json: { ...datos, items: items.slice((pagina - 1) * 4, pagina * 4), pagina, por_pagina: 4, total: 8, total_paginas: 2 } })
  })
  await page.goto('/panel/conocimiento')
  const tarjetas = page.getByRole('list', { name: 'Artículos de la biblioteca' }).getByRole('listitem')
  await expect(tarjetas).toHaveCount(4)
  await page.getByRole('button', { name: 'Siguiente', exact: true }).click()
  await expect(tarjetas.first()).toContainText('Tutorial de monitor 5')
  await expect(tarjetas).toHaveCount(4)
  await page.getByRole('button', { name: 'Anterior', exact: true }).click()
  await expect(tarjetas.first()).toContainText('Tutorial de monitor 1')
  for (const tarjeta of await tarjetas.all()) {
    const cuadro = await tarjeta.boundingBox()
    expect(cuadro!.y + cuadro!.height).toBeLessThanOrEqual(900)
  }
  await page.getByRole('button', { name: 'Nuevo artículo', exact: true }).click()
  const dialogo = page.getByRole('dialog')
  expect((await dialogo.boundingBox())!.width).toBeGreaterThanOrEqual(850)
  expect((await dialogo.getByLabel('Contenido', { exact: true }).boundingBox())!.height).toBeGreaterThanOrEqual(240)
  await expect(dialogo.getByText('Ficha del artículo', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await dialogo.getByRole('button', { name: 'Cancelar', exact: true }).click()
})

