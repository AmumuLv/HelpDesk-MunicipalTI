test('Una respuesta rápida se inserta como borrador y se envía desde el ticket', async ({ page, playwright, baseURL }) => {
  const http = await playwright.request.newContext({ baseURL })
  const admin = await (await http.post('/api/auth/login', { data: { correo: 'admin@demo.local', password: 'Demo12345' } })).json()
  const cabeceras = { Authorization: `Bearer ${admin.access_token}`, 'X-CSRF-Token': admin.csrf_token }
  const nombre = `Plantilla de flujo ${Date.now()}`
  const plantilla = await (await http.post('/api/kb/respuestas-rapidas', { headers: cabeceras, data: { titulo: nombre, cuerpo: 'Comprueba la conexión del monitor.' } })).json()
  try {
    const usuario = await (await http.post('/api/auth/login', { data: { correo: 'usuario1@demo.local', password: 'Demo12345' } })).json()
    const cabUsuario = { Authorization: `Bearer ${usuario.access_token}`, 'X-CSRF-Token': usuario.csrf_token }
    const ajustes = await (await http.get('/api/tickets/ajustes-crear', { headers: cabUsuario })).json()
    const respuesta = await http.post('/api/tickets', { headers: cabUsuario, data: { tipo_problema: ajustes.tipos_problema[0].clave, urgencia: 'me_frena' } })
    expect(respuesta.ok()).toBe(true)
    const { ticket } = await respuesta.json()
    await entrar(page, 'administrador')
    await page.goto(`/panel/tickets/${ticket.id}`)
    await page.getByLabel('Insertar respuesta rápida').selectOption({ label: nombre })
    await expect(page.getByLabel('Escribe un mensaje')).toHaveValue('Comprueba la conexión del monitor.')
    const envio = page.waitForResponse((r) => r.url().endsWith(`/tickets/${ticket.id}/mensajes`) && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'Enviar', exact: true }).click()
    expect((await envio).ok()).toBe(true)
    await expect(page.getByLabel('Escribe un mensaje')).toHaveValue('')
  } finally {
    await http.delete(`/api/kb/respuestas-rapidas/${plantilla.id}`, { headers: cabeceras })
    await http.dispose()
  }
})

