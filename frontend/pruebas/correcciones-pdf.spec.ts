test('historial y críticos no comparten filtros ni pestañas duplicadas', async ({ page }) => {
  await entrar(page, 'administrador')
  const cerrados = page.waitForResponse(r => r.url().includes('/api/tickets?') && new URL(r.url()).searchParams.get('vista') === 'cerrados')
  await page.goto('/panel/cerrados?tab=cerrados&vista=criticos')
  await expect(page.getByRole('tab', { name: 'Historial cerrado', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('tablist', { name: 'Vistas rápidas' })).toHaveCount(0)
  expect((await (await cerrados).json()).items.every((t: { estado: string }) => t.estado === 'cerrado')).toBe(true)
  const respuesta = page.waitForResponse(r => r.url().includes('/api/tickets?') && new URL(r.url()).searchParams.get('vista') === 'criticos')
  await page.getByRole('tab', { name: 'Casos críticos', exact: true }).click()
  const datos = await (await respuesta).json()
  expect(datos.items.every((t: { estado: string }) => t.estado !== 'cerrado')).toBe(true)
  await page.reload()
  await expect(page.getByRole('tab', { name: 'Casos críticos', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: 'Historial cerrado', exact: true }).click()
  await expect(page).toHaveURL(/tab=cerrados/)
  await sinDesbordamiento(page, 'historial')
})

test('limpiar archivos e historial requiere confirmar y muestra el resultado', async ({ page }) => {
  await entrar(page, 'administrador')
  const solicitudes: string[] = []
  await page.route(/\/api\/(exportaciones|auditoria|importacion)(?:\?|$)/, ruta => {
    if (ruta.request().method() !== 'DELETE') return ruta.continue()
    solicitudes.push(new URL(ruta.request().url()).pathname)
    return ruta.fulfill({ json: { eliminados: 2 } })
  })
  for (const [url, titulo] of [['/panel/reportes', 'Limpiar reportes'], ['/panel/equipos/importar', 'Limpiar historial'], ['/panel/auditoria', 'Vaciar auditoría']]) {
    await page.goto(url)
    await page.getByRole('button', { name: titulo, exact: true }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    const antes = solicitudes.length
    await page.getByRole('dialog').getByRole('button', { name: 'Cancelar', exact: true }).click()
    expect(solicitudes.length).toBe(antes)
    await page.getByRole('button', { name: titulo, exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Eliminar definitivamente', exact: true }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
    expect(solicitudes.length).toBe(antes + 1)
  }
})

test('registro muestra componentes ocupados y sugerencias técnicas sin repetir datos únicos', async ({ page }) => {
  await entrar(page, 'administrador')
  await page.goto('/panel/equipos')
  await page.getByRole('button', { name: /Registrar equipo|Nuevo equipo/ }).first().click()
  const formulario = page.getByRole('dialog')
  await formulario.getByRole('button', { name: 'CPU', exact: true }).click()
  await expect(formulario.getByRole('combobox', { name: /Procesador/ })).toBeVisible()
  await expect(formulario.getByRole('combobox', { name: /Memoria RAM/ })).toBeVisible()
  await expect(formulario.getByLabel('Código patrimonial', { exact: true })).toHaveAttribute('autocomplete', 'off')
  await formulario.getByRole('button', { name: 'Continuar', exact: true }).click()
  const existente = await page.evaluate(async () => {
    const r = await fetch('/api/conjuntos', { headers: { Authorization: `Bearer ${sessionStorage.getItem('ma.acceso')}` } })
    return (await r.json()).items.find((c: { total_activos: number }) => c.total_activos > 0)
  })
  expect(existente).toBeTruthy()
  await formulario.getByRole('combobox', { name: 'Zona', exact: true }).selectOption(existente.zona_id)
  await formulario.getByRole('combobox', { name: 'Oficina', exact: true }).selectOption(existente.oficina_id)
  const conjunto = formulario.getByRole('combobox', { name: 'Conjunto', exact: true })
  await expect(conjunto).toBeEnabled()
  await conjunto.selectOption(existente.id)
  await expect(formulario.getByLabel('Numeración de conjuntos')).toBeVisible()
  await expect(formulario.getByText(`Pertenece a: ${existente.nombre}`, { exact: true })).toBeVisible()
  await expect(formulario.getByText(`Número previsto del nuevo equipo: N°${existente.siguiente_numero_equipo}`, { exact: true })).toBeVisible()
  await expect(formulario.getByText(`${existente.total_activos} equipos registrados · ${existente.total_activos + 1} equipos al guardar. El número se confirma al registrar.`, { exact: true })).toBeVisible()
  await formulario.screenshot({ path: '../docs/capturas/pdf-registro-conjuntos.png' })
  await formulario.getByRole('button', { name: 'Continuar', exact: true }).click()
  const alta = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/api/activos'))
  await formulario.getByRole('button', { name: 'Guardar equipo', exact: true }).click()
  const respuesta = await alta
  expect(respuesta.status()).toBe(201)
  const nuevo = await respuesta.json()
  expect(nuevo.numero_equipo).toBe(existente.siguiente_numero_equipo)
  await page.goto(`/panel/equipos/${nuevo.id}`)
  await expect(page.getByText(`Este dispositivo: N°${nuevo.numero_equipo}`, { exact: true })).toBeVisible()
  const oficina = page.locator('section > header').getByRole('link', { name: existente.oficina_nombre, exact: true })
  await expect(oficina).toHaveAttribute('href', `/panel/oficinas/${existente.oficina_id}`)
  await oficina.click()
  await expect(page).toHaveURL(new RegExp(`/panel/oficinas/${existente.oficina_id}$`))
})

