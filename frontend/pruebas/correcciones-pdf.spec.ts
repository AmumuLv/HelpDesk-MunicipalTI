test('registrar ticket muestra resumen, valida y guarda la incidencia con su equipo', async ({ page }) => {
  await entrar(page, 'administrador')
  const datos = await page.evaluate(async () => {
    const headers = { Authorization: `Bearer ${sessionStorage.getItem('ma.acceso')}` }
    const lista = await (await fetch('/api/activos?por_pagina=100', { headers })).json()
    for (const equipo of lista.items.filter((item: { responsable_id?: string }) => item.responsable_id)) {
      const persona = await (await fetch(`/api/usuarios/${equipo.responsable_id}`, { headers })).json()
      if (persona.activo && persona.rol === 'usuario') return { equipo, persona }
    }
    throw new Error('La demo necesita una persona activa con equipo asignado')
  })
  await page.goto('/panel/tickets/nuevo')
  const guardar = page.getByRole('button', { name: 'Registrar ticket', exact: true })
  await expect(guardar).toBeDisabled()
  const elegir = async () => {
    await page.getByLabel('Persona afectada', { exact: true }).clear()
    await page.getByLabel('Persona afectada', { exact: true }).fill(datos.persona.nombre)
    await page.locator('#resultados-persona button').filter({ hasText: datos.persona.nombre }).first().click()
  }
  await elegir()
  await page.getByRole('textbox', { name: 'Asunto', exact: true }).fill('No enciende el monitor de la oficina')
  await page.getByLabel('Descripción', { exact: true }).fill('La pantalla permanece apagada después de revisar el cable de alimentación.')
  await page.getByLabel('Categoría', { exact: true }).selectOption('Hardware')
  await page.getByLabel('Prioridad', { exact: true }).selectOption('alta')
  const seleccionEquipo = page.locator('section').filter({ has: page.getByRole('heading', { name: /Equipo y atención/ }) })
  const origen = seleccionEquipo.getByRole('button', { name: 'Sus equipos', exact: true })
  await expect(origen).toHaveAttribute('aria-pressed', 'true')
  const selector = seleccionEquipo.getByRole('combobox', { name: 'Equipo o computadora afectada', exact: true })
  await expect(selector.locator(`option[value="equipo:${datos.equipo.id}"]`)).toHaveCount(1)
  await selector.selectOption(`equipo:${datos.equipo.id}`)
  await expect(selector).toHaveValue(`equipo:${datos.equipo.id}`)
  await seleccionEquipo.getByRole('button', { name: 'De la oficina', exact: true }).click()
  await expect(selector).toHaveValue('')
  await seleccionEquipo.getByRole('button', { name: 'Sus equipos', exact: true }).click()
  await selector.selectOption(`equipo:${datos.equipo.id}`)
  await elegir()
  await expect(selector).toHaveValue('')
  await selector.selectOption(`equipo:${datos.equipo.id}`)
  const resumen = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Resumen del ticket', exact: true }) })
  await expect(resumen.getByText('No enciende el monitor de la oficina', { exact: true })).toBeVisible()
  await expect(resumen.getByText('Alta', { exact: true })).toBeVisible()
  await expect(guardar).toBeEnabled()
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect(page.getByRole('heading', { name: 'Registrar ticket', exact: true })).toBeInViewport()
  await page.screenshot({ path: '../docs/capturas/registrar-ticket-redisenado.png', fullPage: true })
  await page.getByRole('button', { name: 'Cambiar a tema oscuro', exact: true }).click()
  await page.screenshot({ path: '../docs/capturas/registrar-ticket-oscuro.png', fullPage: true })
  for (const ancho of [390, 820]) {
    await page.setViewportSize({ width: ancho, height: 900 })
    await sinDesbordamiento(page, `Registrar ticket a ${ancho}px`)
  }
  await page.route('**/api/tickets/manual', ruta => ruta.fulfill({ status: 503, json: { mensaje: 'Servicio temporalmente no disponible', codigo: 'no_disponible' } }), { times: 1 })
  await guardar.click()
  await expect(page.getByRole('alert').filter({ hasText: 'Servicio temporalmente no disponible' })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Asunto', exact: true })).toHaveValue('No enciende el monitor de la oficina')
  const respuesta = page.waitForResponse(r => r.url().endsWith('/api/tickets/manual') && r.request().method() === 'POST')
  await guardar.click()
  const r = await respuesta
  expect(r.status()).toBe(201)
  const enviado = r.request().postDataJSON()
  expect(enviado.persona.afectado_id).toBe(datos.persona.id)
  expect(enviado.activo_id).toBeTruthy()
  expect(enviado.prioridad).toBe('alta')
  const creado = await r.json()
  await expect(page).toHaveURL(new RegExp(`/panel/tickets/${creado.ticket.id}$`))
  await expect(page.getByRole('heading', { name: 'No enciende el monitor de la oficina', exact: true })).toBeVisible()
})

test('ficha del ticket destaca el problema, conserva enlaces y se adapta al móvil', async ({ page }) => {
  await entrar(page, 'administrador')
  const ticket = await page.evaluate(async () => {
    const r = await fetch('/api/tickets?por_pagina=1', { headers: { Authorization: `Bearer ${sessionStorage.getItem('ma.acceso')}` } })
    return (await r.json()).items[0]
  })
  expect(ticket?.id).toBeTruthy()
  let conTipo = true
  const nombreLargo = 'Nombre de la persona que reporta '.repeat(10)
  await page.route(`**/api/tickets/${ticket.id}`, async ruta => {
    const respuesta = await ruta.fetch()
    await ruta.fulfill({ json: { ...await respuesta.json(), tipo_problema: conTipo ? 'El equipo no enciende' : null, asunto: 'Pantalla sin señal', descripcion: 'Al encender el monitor no aparece imagen.\nSe revisó la conexión eléctrica.', reportante_nombre: nombreLargo, activo_id: 'abcdefabcdefabcdefabcdef', activo_nombre: 'MONITOR-OFICINA', activo_tipo: 'Monitor', puede_cerrar: true, estado: 'nuevo' } })
  })
  await page.goto(`/panel/tickets/${ticket.id}`)
  const ficha = page.getByRole('region', { name: 'Incidencia reportada', exact: true })
  await expect(ficha.getByRole('heading', { name: 'Pantalla sin señal', exact: true })).toBeVisible()
  await expect(ficha.getByText('Al encender el monitor no aparece imagen.', { exact: false })).toBeVisible()
  await expect(ficha.getByRole('link', { name: 'MONITOR-OFICINA', exact: true })).toHaveAttribute('href', '/panel/equipos/abcdefabcdefabcdefabcdef')
  await expect(ficha.getByTitle(nombreLargo, { exact: true })).toHaveCSS('text-overflow', 'ellipsis')
  await expect(page.getByRole('button', { name: 'Asignar', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Cerrar ticket', exact: true }).click()
  const dialogo = page.getByRole('dialog', { name: 'Cerrar ticket', exact: true })
  await expect(dialogo).toBeVisible()
  await expect(dialogo.getByRole('button', { name: 'Cerrar ticket', exact: true })).toBeDisabled()
  await dialogo.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect(page.getByRole('heading', { name: ticket.codigo, exact: true })).toBeInViewport()
  await page.screenshot({ path: '../docs/capturas/ticket-detalle-redisenado.png', fullPage: true })
  for (const ancho of [390, 820]) {
    await page.setViewportSize({ width: ancho, height: 900 })
    await sinDesbordamiento(page, `Ficha del ticket a ${ancho}px`)
    await expect(ficha.getByRole('heading', { name: 'Pantalla sin señal', exact: true })).toBeVisible()
  }
  conTipo = false
  await page.reload()
  await expect(ficha.getByRole('heading', { name: 'Pantalla sin señal', exact: true })).toBeVisible()
  await page.evaluate(() => localStorage.setItem('ma.tema', 'oscuro'))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.reload()
  await expect(ficha.getByRole('heading', { name: 'Pantalla sin señal', exact: true })).toBeVisible()
  await sinDesbordamiento(page, 'Ficha del ticket en tema oscuro')
  await page.screenshot({ path: '../docs/capturas/ticket-detalle-oscuro.png', fullPage: true })
})

